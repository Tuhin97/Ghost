def check_device_offline(
    device_id: str,
    last_seen: datetime,
) -> Optional[Alert]:
    """
    Check if a device has been offline too long.

    Args:
        device_id:  which device
        last_seen:  when we last heard from it

    Returns:
        Alert if offline too long, None if recently seen
    """
    now = datetime.now(timezone.utc)

    # Make last_seen timezone-aware if it isn't already
    if last_seen.tzinfo is None:
        last_seen = last_seen.replace(tzinfo=timezone.utc)

    seconds_offline = (now - last_seen).total_seconds()

    if seconds_offline >= config.DEVICE_OFFLINE_SECONDS:
        return Alert(
            level=AlertLevel.WARNING,
            device_id=device_id,
            metric="offline",
            value=seconds_offline,
            threshold=config.DEVICE_OFFLINE_SECONDS,
            message=(
                f"{device_id} has been offline for "
                f"{int(seconds_offline)}s. "
                f"Is it powered on?"
            )
        )

    return None


def check_all(
    device_id: str,
    disk_pct: float,
    cpu_pct: float,
    ram_pct: float,
) -> list[Alert]:
    """
    Run all checks for a device and return any alerts.

    This is the main function called by the poller.
    Runs every check and collects all alerts in one call.

    Args:
        device_id:  which device
        disk_pct:   disk usage percentage
        cpu_pct:    CPU usage percentage
        ram_pct:    RAM usage percentage

    Returns:
        list of Alert objects — empty if everything is fine
    """
    alerts = []

    # Run each check — add to list if alert returned
    for check_result in [
        check_disk(device_id, disk_pct),
        check_cpu(device_id, cpu_pct),
        check_ram(device_id, ram_pct),
    ]:
        if check_result is not None:
            alerts.append(check_result)

    return alerts
