"""
monitor/rules.py — Rules engine for system monitoring.

No LLM involved — pure threshold checks.
Fast, cheap, and reliable for obvious alerts.

Rules:
  disk > 85%           → WARNING
  disk > 95%           → CRITICAL
  CPU > 90% sustained  → WARNING  
  RAM > 90%            → WARNING
  device offline 90s   → ALERT
"""

from dataclasses import dataclass
from datetime import datetime, timezone
from enum import Enum
from typing import Optional

import config


class AlertLevel(Enum):
    """
    Alert severity levels.
    Using an Enum means we can never typo a level name —
    Python will catch it at runtime.
    """
    INFO     = "info"
    WARNING  = "warning"
    CRITICAL = "critical"


@dataclass
class Alert:
    """
    Represents one alert generated by the rules engine.

    @dataclass auto-generates __init__ and __repr__
    so we don't have to write boilerplate.
    """
    level:     AlertLevel
    device_id: str
    metric:    str        # what triggered it — "disk", "cpu", "ram", "offline"
    value:     float      # the actual measured value
    threshold: float      # the threshold that was crossed
    message:   str        # human readable description
    ts:        str = ""   # timestamp — set automatically in __post_init__

    def __post_init__(self):
        """
        __post_init__ runs automatically after __init__ in a dataclass.
        We use it to set the timestamp automatically on creation.
        """
        if not self.ts:
            self.ts = datetime.now(timezone.utc).isoformat()

    def to_dict(self) -> dict:
        """Convert to dictionary for WebSocket broadcast."""
        return {
            "type":      "alert",
            "level":     self.level.value,
            "device_id": self.device_id,
            "metric":    self.metric,
            "value":     self.value,
            "threshold": self.threshold,
            "message":   self.message,
            "ts":        self.ts,
        }


def check_disk(device_id: str, usage_pct: float) -> Optional[Alert]:
    """
    Check disk usage against thresholds.

    Args:
        device_id:  which device — "thinkpad", "macbook" etc
        usage_pct:  disk usage as percentage — e.g. 87.5

    Returns:
        Alert if threshold crossed, None if all good
    """
    if usage_pct >= config.DISK_CRIT_PCT:
        return Alert(
            level=AlertLevel.CRITICAL,
            device_id=device_id,
            metric="disk",
            value=usage_pct,
            threshold=config.DISK_CRIT_PCT,
            message=(
                f"{device_id} disk is critically full at {usage_pct:.1f}%. "
                f"Immediate cleanup needed."
            )
        )

    if usage_pct >= config.DISK_WARN_PCT:
        return Alert(
            level=AlertLevel.WARNING,
            device_id=device_id,
            metric="disk",
            value=usage_pct,
            threshold=config.DISK_WARN_PCT,
            message=(
                f"{device_id} disk at {usage_pct:.1f}%. "
                f"Getting full — consider cleaning up."
            )
        )

    return None


